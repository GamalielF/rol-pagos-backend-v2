-- =====================================================================================================
-- V11. Los usuarios pasan a tener un ID secuencial propio (clave sustituta).
--
-- Antes: cada tabla guardaba el código del AD como texto (USERNAME_AD = 'fsepa') y nada garantizaba que
-- existiera. Ahora: una tabla USUARIOS con ID BIGINT AUTO_INCREMENT, y las demás la referencian por
-- USUARIO_ID con una FOREIGN KEY. Los datos existentes se conservan: primero se crean los usuarios a partir
-- de todos los códigos que ya aparecen en la base, después cada tabla se enlaza y recién al final se borra
-- la columna de texto.
-- =====================================================================================================

-- 1) La tabla de usuarios. Es la identidad del sistema: NO depende del AD (un usuario puede existir antes
--    de la primera sincronización, como los administradores de arranque, o haber sido dado de baja).
CREATE TABLE USUARIOS (
                          ID                 BIGINT       NOT NULL AUTO_INCREMENT,
                          USERNAME_AD        VARCHAR(50)  NOT NULL,
                          ESTADO_REGISTRO    VARCHAR(10)  NOT NULL DEFAULT 'ACTIVO',
                          CREADO_POR         VARCHAR(100) NOT NULL,
                          CREADO_EN          DATETIME(6)  NOT NULL,
                          MODIFICADO_POR     VARCHAR(100) NOT NULL,
                          MODIFICADO_EN      DATETIME(6)  NOT NULL,
                          VERSION            BIGINT       NOT NULL DEFAULT 0,
                          CONSTRAINT PK_USUARIOS PRIMARY KEY (ID),
                          CONSTRAINT UK_USUARIOS_USERNAME UNIQUE (USERNAME_AD),
                          CONSTRAINT CK_USUARIOS_ESTADO_REGISTRO CHECK (ESTADO_REGISTRO IN ('ACTIVO', 'INACTIVO'))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = 'Identidad de cada usuario del sistema; las demas tablas lo referencian por ID';

-- 2) El actor de los procesos automáticos (sincronización, envío de avisos) también es un usuario.
INSERT INTO USUARIOS (USERNAME_AD, CREADO_POR, CREADO_EN, MODIFICADO_POR, MODIFICADO_EN)
VALUES ('SISTEMA', 'SISTEMA', NOW(6), 'SISTEMA', NOW(6));

-- 3) Todos los códigos que ya existen en la base. UNION quita los repetidos; la intercalación de MySQL no
--    distingue mayúsculas, así que 'FSEPA' y 'fsepa' quedan como un solo usuario. Primero los del directorio
--    (en su orden), para que sus ID sigan el mismo orden.
INSERT INTO USUARIOS (USERNAME_AD, CREADO_POR, CREADO_EN, MODIFICADO_POR, MODIFICADO_EN)
SELECT u.USERNAME_AD, 'SISTEMA', NOW(6), 'SISTEMA', NOW(6)
FROM (SELECT USERNAME_AD, MIN(ID) AS ORDEN FROM DIRECTORIO_AD GROUP BY USERNAME_AD
      UNION ALL
      SELECT USERNAME_AD, 1000000000 FROM ASIGNACIONES_ROL
      UNION ALL
      SELECT USERNAME_AD, 1000000000 FROM ACCESOS_ROLES_PAGO
      UNION ALL
      SELECT USERNAME_AD, 1000000000 FROM ACCIONES_ROLES_PAGO
      UNION ALL
      SELECT USERNAME_DESTINO, 1000000000 FROM NOTIFICACIONES_ROLES_PAGO WHERE USERNAME_DESTINO IS NOT NULL
      UNION ALL
      SELECT PUBLICADO_POR, 1000000000 FROM PERIODOS WHERE PUBLICADO_POR IS NOT NULL) u
WHERE u.USERNAME_AD <> 'SISTEMA'
GROUP BY u.USERNAME_AD
ORDER BY MIN(u.ORDEN), u.USERNAME_AD;

-- 4) Cada tabla: columna nueva -> se llena desde USUARIOS -> obligatoria -> clave foránea -> fuera el texto.

-- 4a) DIRECTORIO_AD: cada cuenta del AD es exactamente un usuario (relación 1 a 1).
ALTER TABLE DIRECTORIO_AD ADD COLUMN USUARIO_ID BIGINT NULL AFTER ID;
UPDATE DIRECTORIO_AD d JOIN USUARIOS u ON u.USERNAME_AD = d.USERNAME_AD SET d.USUARIO_ID = u.ID;
ALTER TABLE DIRECTORIO_AD MODIFY USUARIO_ID BIGINT NOT NULL;
ALTER TABLE DIRECTORIO_AD ADD CONSTRAINT UK_DIRECTORIO_AD_USUARIO UNIQUE (USUARIO_ID);
ALTER TABLE DIRECTORIO_AD ADD CONSTRAINT FK_DIRECTORIO_AD_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIOS (ID);
ALTER TABLE DIRECTORIO_AD DROP INDEX UK_DIRECTORIO_AD_USERNAME;
ALTER TABLE DIRECTORIO_AD DROP COLUMN USERNAME_AD;

-- 4b) ASIGNACIONES_ROL: un usuario no puede tener el mismo rol dos veces.
ALTER TABLE ASIGNACIONES_ROL ADD COLUMN USUARIO_ID BIGINT NULL AFTER ID;
UPDATE ASIGNACIONES_ROL a JOIN USUARIOS u ON u.USERNAME_AD = a.USERNAME_AD SET a.USUARIO_ID = u.ID;
ALTER TABLE ASIGNACIONES_ROL MODIFY USUARIO_ID BIGINT NOT NULL;
ALTER TABLE ASIGNACIONES_ROL ADD CONSTRAINT FK_ASIGNACIONES_ROL_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIOS (ID);
ALTER TABLE ASIGNACIONES_ROL ADD CONSTRAINT UK_ASIGNACIONES_ROL_USUARIO_ID_ROL UNIQUE (USUARIO_ID, ROL);
ALTER TABLE ASIGNACIONES_ROL DROP INDEX UK_ASIGNACIONES_ROL_USUARIO_ROL;
ALTER TABLE ASIGNACIONES_ROL DROP COLUMN USERNAME_AD;

-- 4c) ACCESOS_ROLES_PAGO: quién consultó un rol.
ALTER TABLE ACCESOS_ROLES_PAGO ADD COLUMN USUARIO_ID BIGINT NULL AFTER DETALLE;
UPDATE ACCESOS_ROLES_PAGO a JOIN USUARIOS u ON u.USERNAME_AD = a.USERNAME_AD SET a.USUARIO_ID = u.ID;
ALTER TABLE ACCESOS_ROLES_PAGO MODIFY USUARIO_ID BIGINT NOT NULL;
ALTER TABLE ACCESOS_ROLES_PAGO ADD CONSTRAINT FK_ACCESOS_ROLES_PAGO_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIOS (ID);
CREATE INDEX IDX_ACCESOS_ROLES_PAGO_USUARIO_ID ON ACCESOS_ROLES_PAGO (USUARIO_ID, CREADO_EN);
DROP INDEX IDX_ACCESOS_ROLES_PAGO_USUARIO ON ACCESOS_ROLES_PAGO;
ALTER TABLE ACCESOS_ROLES_PAGO DROP COLUMN USERNAME_AD;

-- 4d) ACCIONES_ROLES_PAGO: quién hizo cada acción de gestión.
ALTER TABLE ACCIONES_ROLES_PAGO ADD COLUMN USUARIO_ID BIGINT NULL AFTER TIPO_ACCION;
UPDATE ACCIONES_ROLES_PAGO a JOIN USUARIOS u ON u.USERNAME_AD = a.USERNAME_AD SET a.USUARIO_ID = u.ID;
ALTER TABLE ACCIONES_ROLES_PAGO MODIFY USUARIO_ID BIGINT NOT NULL;
ALTER TABLE ACCIONES_ROLES_PAGO ADD CONSTRAINT FK_ACCIONES_ROLES_PAGO_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIOS (ID);
CREATE INDEX IDX_ACCIONES_ROLES_PAGO_USUARIO_ID ON ACCIONES_ROLES_PAGO (USUARIO_ID, CREADO_EN);
DROP INDEX IDX_ACCIONES_ROLES_PAGO_USUARIO ON ACCIONES_ROLES_PAGO;
ALTER TABLE ACCIONES_ROLES_PAGO DROP COLUMN USERNAME_AD;

-- 4e) NOTIFICACIONES_ROLES_PAGO: a qué cuenta se envió el aviso. Opcional: una cédula puede no tener cuenta.
ALTER TABLE NOTIFICACIONES_ROLES_PAGO ADD COLUMN USUARIO_DESTINO_ID BIGINT NULL AFTER CEDULA;
UPDATE NOTIFICACIONES_ROLES_PAGO n JOIN USUARIOS u ON u.USERNAME_AD = n.USERNAME_DESTINO SET n.USUARIO_DESTINO_ID = u.ID;
ALTER TABLE NOTIFICACIONES_ROLES_PAGO ADD CONSTRAINT FK_NOTIFICACIONES_USUARIO_DESTINO FOREIGN KEY (USUARIO_DESTINO_ID) REFERENCES USUARIOS (ID);
ALTER TABLE NOTIFICACIONES_ROLES_PAGO DROP COLUMN USERNAME_DESTINO;

-- 4f) PERIODOS: quién publicó el mes. Opcional: un período recién cargado aún no se publica.
ALTER TABLE PERIODOS ADD COLUMN PUBLICADO_POR_ID BIGINT NULL AFTER FECHA_PUBLICACION;
UPDATE PERIODOS p JOIN USUARIOS u ON u.USERNAME_AD = p.PUBLICADO_POR SET p.PUBLICADO_POR_ID = u.ID;
ALTER TABLE PERIODOS ADD CONSTRAINT FK_PERIODOS_PUBLICADO_POR FOREIGN KEY (PUBLICADO_POR_ID) REFERENCES USUARIOS (ID);
ALTER TABLE PERIODOS DROP COLUMN PUBLICADO_POR;
